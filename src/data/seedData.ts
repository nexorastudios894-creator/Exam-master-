function makeOptions(
  questionId: string,
  items: [string, string, string, string],
  correctIndex: 0 | 1 | 2 | 3
): Option[] {
  const labels: Array<'A' | 'B' | 'C' | 'D'> = ['A', 'B', 'C', 'D'];
  return items.map((text, idx) => ({
    id: `${questionId}-opt-${labels[idx]}`,
    questionId,
    label: labels[idx],
    text,
    isCorrect: idx === correctIndex,
  }));
}

function q(
  id: string,
  examCode: ExamCode,
  subjectId: string,
  subjectName: string,
  year: number,
  topic: string,
  prompt: string,
  options: [string, string, string, string],
  correctIndex: 0 | 1 | 2 | 3,
  explanation: string,
  difficulty: 'easy' | 'medium' | 'hard' = 'medium',
  passage?: string
): Question {
  return {
    id,
    examId: `exam-${examCode.toLowerCase()}`,
    examCode,
    subjectId,
    subjectName,
    year,
    topic,
    passage,
    prompt,
    options: makeOptions(id, options, correctIndex),
    explanation,
    difficulty,
    createdAt: '2026-09-10T09:00:00.000Z',
  };
}

